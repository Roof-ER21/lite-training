import {test,expect} from '@playwright/test';
test('refresh keeps question order and all answer types without consuming another attempt',async ({page})=>{
 await page.route('**/api/**',r=>r.fulfill({status:503,json:{offline:true}}));
 await page.route('**/api/exam/start',r=>r.fulfill({json:{attemptId:'11111111-1111-4111-8111-111111111111',remainingAttempts:3}}));
 await page.goto('/');
 await page.getByLabel('Your Name').fill('Exam Recovery QA');
 await page.getByRole('button',{name:'Start Training',exact:true}).click();
 await expect(page.locator('#learning-path li')).toHaveCount(14);
 await page.evaluate(()=>{localStorage.setItem('roof-er.unlockedModules',JSON.stringify(['welcome','final-exam']));(window as any).navigateToModule('final-exam');});
 await page.locator('#exam-user-name').fill('Exam Recovery QA');
 await page.locator('#startFinalExam').click();
 const question=await page.locator('.mcq-question').first().getAttribute('data-id');
 await page.locator('input[name="mcq-0"]').nth(2).check();
 await page.locator('[name="fib-0"]').fill('saved fill answer');
 await page.locator('[name="sa-0"]').fill('saved long answer');
 await page.reload();
 await expect(page.locator('#learning-path li')).toHaveCount(14);
 await page.evaluate(()=>(window as any).navigateToModule('final-exam'));
 await expect(page.locator('.mcq-question').first()).toHaveAttribute('data-id',question!);
 await expect(page.locator('input[name="mcq-0"]').nth(2)).toBeChecked();
 await expect(page.locator('[name="fib-0"]')).toHaveValue('saved fill answer');
 await expect(page.locator('[name="sa-0"]')).toHaveValue('saved long answer');
 await expect(page.locator('.exam-attempt-indicator')).toContainText('Attempt 1');
 await page.locator('.mcq-question').evaluateAll(nodes=>nodes.forEach(n=>{const input=n.querySelector('input') as HTMLInputElement; input.checked=true;input.dispatchEvent(new Event('change'));}));
 await page.locator('.fib-input, .sa-input').evaluateAll(nodes=>nodes.forEach(n=>{(n as HTMLInputElement).value='test response';n.dispatchEvent(new Event('input'));}));
 page.on('dialog',d=>d.accept());
 await page.locator('#submitExam').click();
 await expect(page.locator('#exam-save-error')).toContainText('Submission not confirmed');
 expect(await page.evaluate(()=>localStorage.getItem('roof-er.certifiedStatus'))).not.toBe('true');
 const payloads:any[]=[];
 await page.route('**/api/exam/submit',r=>{payloads.push(r.request().postDataJSON());return r.fulfill({json:{success:true,passed:false,score:20}});});
 await page.reload();
 await expect(page.locator('#learning-path li')).toHaveCount(14);
 await page.evaluate(()=>(window as any).navigateToModule('final-exam'));
 await expect(page.locator('#exam-save-error')).toContainText('confirmation is pending');
 await page.locator('#submitExam').click();
 await expect(page.locator('#submitExam')).toHaveCount(0);
 expect(payloads).toHaveLength(1);
 expect(payloads[0].attemptId).toBe('11111111-1111-4111-8111-111111111111');
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roof-er.finalExamHistory')||'[]').length)).toBe(1);
});
